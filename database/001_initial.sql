PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS auth_sessions (
 token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at REAL NOT NULL
);
CREATE TABLE IF NOT EXISTS calls (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 title TEXT NOT NULL, mode TEXT NOT NULL, score INTEGER NOT NULL DEFAULT 0,
 status TEXT NOT NULL DEFAULT 'active', created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
 retain_transcript INTEGER NOT NULL DEFAULT 0,
 turn_count INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS turns (
 id INTEGER PRIMARY KEY AUTOINCREMENT, call_id TEXT NOT NULL REFERENCES calls(id) ON DELETE CASCADE,
 position INTEGER NOT NULL, text TEXT NOT NULL, analysis TEXT NOT NULL,
 UNIQUE(call_id, position)
);
CREATE TABLE IF NOT EXISTS contacts (
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 name TEXT NOT NULL, phone TEXT NOT NULL, relationship TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (
 user_id TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 retain_transcript INTEGER NOT NULL DEFAULT 0, spoken_warnings INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS calls_owner ON calls(user_id, created_at);
